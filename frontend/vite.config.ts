import fs from 'node:fs';
import path from 'node:path';
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';

/** Where the engine's pre-rendered layer HTML lives during development. */
const LAYER_DIR = path.resolve(__dirname, '../HTML');
const LAYER_ROUTE = '/layers/';

/**
 * Serves the engine's generated layer HTML in dev.
 *
 * These files are large (the sample is 8.6 MB) and are complete pydeck
 * documents, so they are streamed straight off disk rather than going through
 * Vite's transform pipeline or the app bundle. In production FastAPI serves
 * the same route and this plugin does nothing.
 */
function serveLayerHtml(): Plugin {
  return {
    name: 'maphex-serve-layer-html',
    apply: 'serve',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const url = req.url ?? '';
        if (!url.startsWith(LAYER_ROUTE)) return next();

        // Strip the query string, then resolve inside LAYER_DIR only — a
        // request for ../../etc/passwd must not escape the folder.
        const requested = decodeURIComponent(url.slice(LAYER_ROUTE.length).split('?')[0]);
        const file = path.resolve(LAYER_DIR, requested);
        if (!file.startsWith(LAYER_DIR + path.sep)) {
          res.statusCode = 403;
          res.end('Forbidden');
          return;
        }

        if (!fs.existsSync(file) || !fs.statSync(file).isFile()) {
          res.statusCode = 404;
          res.setHeader('Content-Type', 'text/plain; charset=utf-8');
          res.end(`No layer HTML at ${requested}. Expected it in ${LAYER_DIR}.`);
          return;
        }

        res.setHeader('Content-Type', 'text/html; charset=utf-8');
        res.setHeader('Content-Length', fs.statSync(file).size);
        // Regenerated by the engine, so never cache it in dev.
        res.setHeader('Cache-Control', 'no-store');
        fs.createReadStream(file).pipe(res);
      });
    },
  };
}

export default defineConfig({
  plugins: [react(), serveLayerHtml()],
  optimizeDeps: {
    // maplibre-gl loads its worker from a separate module URL. Vite's
    // pre-bundling rewrites that URL to a file it never emits, so the worker
    // 404s and the base map silently stays blank. Serving maplibre unbundled
    // lets Vite resolve the worker the normal way.
    exclude: ['maplibre-gl'],
  },
  server: {
    port: 5173,
    proxy: {
      // Forwards to uvicorn in dev. Nothing uses it yet — the UI runs against
      // the mock adapter in src/api/mock — but it is here so the switch to the
      // real backend needs no config change.
      '/api': {
        target: 'http://127.0.0.1:8000',
        changeOrigin: true,
      },
    },
  },
  build: {
    // FastAPI serves this directory once the backend exists.
    outDir: 'dist',
  },
});
